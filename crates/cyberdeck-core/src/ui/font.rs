//! Embedded 5x7 bitmap font used by the device UI.
//!
//! Column-major: each glyph is five bytes, one per column, bit 0 = top row.
//! Lowercase is folded to uppercase (the reference firmware's menus are uppercase
//! too); unsupported characters render as a hollow box so a bad SSID can never
//! leave holes in the layout.

/// Glyph width in pixels.
pub const GLYPH_W: u8 = 5;
/// Glyph height in pixels.
pub const GLYPH_H: u8 = 7;
/// Horizontal advance including one column of spacing.
pub const ADVANCE: u8 = 6;
/// Line height including two rows of spacing.
pub const LINE_HEIGHT: u8 = 10;

const BOX: [u8; 5] = [0x7F, 0x41, 0x41, 0x41, 0x7F];

/// Look up a glyph, folding lowercase to uppercase.
pub fn glyph(ch: char) -> &'static [u8; 5] {
    let upper = ch.to_ascii_uppercase();
    match upper {
        ' ' => &[0x00, 0x00, 0x00, 0x00, 0x00],
        '!' => &[0x00, 0x00, 0x5F, 0x00, 0x00],
        '"' => &[0x00, 0x07, 0x00, 0x07, 0x00],
        '#' => &[0x14, 0x7F, 0x14, 0x7F, 0x14],
        '$' => &[0x24, 0x2A, 0x7F, 0x2A, 0x12],
        '%' => &[0x23, 0x13, 0x08, 0x64, 0x62],
        '&' => &[0x36, 0x49, 0x55, 0x22, 0x50],
        '\'' => &[0x00, 0x05, 0x03, 0x00, 0x00],
        '(' => &[0x00, 0x1C, 0x22, 0x41, 0x00],
        ')' => &[0x00, 0x41, 0x22, 0x1C, 0x00],
        '*' => &[0x14, 0x08, 0x3E, 0x08, 0x14],
        '+' => &[0x08, 0x08, 0x3E, 0x08, 0x08],
        ',' => &[0x00, 0x50, 0x30, 0x00, 0x00],
        '-' => &[0x08, 0x08, 0x08, 0x08, 0x08],
        '.' => &[0x00, 0x60, 0x60, 0x00, 0x00],
        '/' => &[0x20, 0x10, 0x08, 0x04, 0x02],
        '0' => &[0x3E, 0x51, 0x49, 0x45, 0x3E],
        '1' => &[0x00, 0x42, 0x7F, 0x40, 0x00],
        '2' => &[0x42, 0x61, 0x51, 0x49, 0x46],
        '3' => &[0x21, 0x41, 0x45, 0x4B, 0x31],
        '4' => &[0x18, 0x14, 0x12, 0x7F, 0x10],
        '5' => &[0x27, 0x45, 0x45, 0x45, 0x39],
        '6' => &[0x3C, 0x4A, 0x49, 0x49, 0x30],
        '7' => &[0x01, 0x71, 0x09, 0x05, 0x03],
        '8' => &[0x36, 0x49, 0x49, 0x49, 0x36],
        '9' => &[0x06, 0x49, 0x49, 0x29, 0x1E],
        ':' => &[0x00, 0x36, 0x36, 0x00, 0x00],
        ';' => &[0x00, 0x56, 0x36, 0x00, 0x00],
        '<' => &[0x08, 0x14, 0x22, 0x41, 0x00],
        '=' => &[0x14, 0x14, 0x14, 0x14, 0x14],
        '>' => &[0x00, 0x41, 0x22, 0x14, 0x08],
        '?' => &[0x02, 0x01, 0x51, 0x09, 0x06],
        '@' => &[0x32, 0x49, 0x79, 0x41, 0x3E],
        'A' => &[0x7E, 0x11, 0x11, 0x11, 0x7E],
        'B' => &[0x7F, 0x49, 0x49, 0x49, 0x36],
        'C' => &[0x3E, 0x41, 0x41, 0x41, 0x22],
        'D' => &[0x7F, 0x41, 0x41, 0x22, 0x1C],
        'E' => &[0x7F, 0x49, 0x49, 0x49, 0x41],
        'F' => &[0x7F, 0x09, 0x09, 0x09, 0x01],
        'G' => &[0x3E, 0x41, 0x49, 0x49, 0x7A],
        'H' => &[0x7F, 0x08, 0x08, 0x08, 0x7F],
        'I' => &[0x00, 0x41, 0x7F, 0x41, 0x00],
        'J' => &[0x20, 0x40, 0x41, 0x3F, 0x01],
        'K' => &[0x7F, 0x08, 0x14, 0x22, 0x41],
        'L' => &[0x7F, 0x40, 0x40, 0x40, 0x40],
        'M' => &[0x7F, 0x02, 0x0C, 0x02, 0x7F],
        'N' => &[0x7F, 0x04, 0x08, 0x10, 0x7F],
        'O' => &[0x3E, 0x41, 0x41, 0x41, 0x3E],
        'P' => &[0x7F, 0x09, 0x09, 0x09, 0x06],
        'Q' => &[0x3E, 0x41, 0x51, 0x21, 0x5E],
        'R' => &[0x7F, 0x09, 0x19, 0x29, 0x46],
        'S' => &[0x46, 0x49, 0x49, 0x49, 0x31],
        'T' => &[0x01, 0x01, 0x7F, 0x01, 0x01],
        'U' => &[0x3F, 0x40, 0x40, 0x40, 0x3F],
        'V' => &[0x1F, 0x20, 0x40, 0x20, 0x1F],
        'W' => &[0x7F, 0x20, 0x18, 0x20, 0x7F],
        'X' => &[0x63, 0x14, 0x08, 0x14, 0x63],
        'Y' => &[0x03, 0x04, 0x78, 0x04, 0x03],
        'Z' => &[0x61, 0x51, 0x49, 0x45, 0x43],
        '[' => &[0x00, 0x7F, 0x41, 0x41, 0x00],
        '\\' => &[0x02, 0x04, 0x08, 0x10, 0x20],
        ']' => &[0x00, 0x41, 0x41, 0x7F, 0x00],
        '^' => &[0x04, 0x02, 0x01, 0x02, 0x04],
        '_' => &[0x40, 0x40, 0x40, 0x40, 0x40],
        '`' => &[0x00, 0x01, 0x02, 0x04, 0x00],
        '{' => &[0x08, 0x36, 0x41, 0x00, 0x00],
        '|' => &[0x00, 0x00, 0x7F, 0x00, 0x00],
        '}' => &[0x00, 0x00, 0x41, 0x36, 0x08],
        '~' => &[0x10, 0x08, 0x08, 0x10, 0x08],
        // UI-only glyphs.
        '\u{2192}' => &[0x08, 0x1C, 0x2A, 0x08, 0x08], // right arrow
        '\u{00B0}' => &[0x00, 0x06, 0x09, 0x09, 0x06], // degree
        _ => &BOX,
    }
}

/// Width in pixels of `text` at `scale`.
pub fn text_width(text: &str, scale: u8) -> u16 {
    let scale = u16::from(scale.max(1));
    text.chars().count() as u16 * u16::from(ADVANCE) * scale
}

/// Characters that fit in `width` pixels at `scale`.
pub fn chars_per_line(width: u16, scale: u8) -> usize {
    let advance = u16::from(ADVANCE).max(1) * u16::from(scale.max(1));
    (width / advance).max(1) as usize
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_fit_the_cell() {
        let chars = " !\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`{|}~\u{2192}\u{00B0}";
        for ch in chars.chars() {
            let glyph = glyph(ch);
            // 5 columns; only the low 7 bits are used (7-pixel height).
            assert!(
                glyph.iter().all(|column| *column & 0x80 == 0),
                "column bits above row 6 set for {ch:?}"
            );
        }
    }

    #[test]
    fn letters_are_distinct() {
        let mut seen = alloc::vec::Vec::new();
        for ch in 'A'..='Z' {
            let g = *glyph(ch);
            assert!(g.iter().any(|c| *c != 0), "{ch} is blank");
            assert!(!seen.contains(&g), "{ch} duplicates another glyph");
            seen.push(g);
        }
        for ch in '0'..='9' {
            let g = *glyph(ch);
            assert!(!seen.contains(&g), "{ch} duplicates another glyph");
            seen.push(g);
        }
    }

    #[test]
    fn lowercase_folds_to_uppercase() {
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph('z'), glyph('Z'));
    }

    #[test]
    fn unknown_characters_render_as_box() {
        assert_eq!(glyph('\u{4E2D}'), &BOX);
        assert_eq!(glyph('\t'), &BOX);
    }

    #[test]
    fn metrics_are_consistent() {
        assert_eq!(text_width("ABC", 1), 18);
        assert_eq!(text_width("ABC", 2), 36);
        assert_eq!(chars_per_line(240, 1), 40);
        assert_eq!(chars_per_line(240, 2), 20);
        assert_eq!(chars_per_line(10, 4), 1);
    }
}
